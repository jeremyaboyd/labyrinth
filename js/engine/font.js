// draw text at pixel coords on a 2d context. scale = integer pixel scale.
function drawText(ctx, text, x, y, color, scale) {
  scale = scale || 1;
  ctx.fillStyle = color;
  text = String(text).toUpperCase();
  let cx = x;
  for (let i = 0; i < text.length; i++) {
    const g = FONT[text[i]];
    if (g) {
      for (let r = 0; r < 7; r++) {
        const bits = g[r];
        if (!bits) continue;
        for (let c = 0; c < 5; c++) {
          if (bits & (0x10 >> c)) {
            ctx.fillRect(cx + c * scale, y + r * scale, scale, scale);
          }
        }
      }
    }
    cx += 6 * scale;
  }
  return cx - x;
}

function textWidth(text, scale) {
  return String(text).length * 6 * (scale || 1) - (scale || 1);
}

// draw with a 1px drop shadow for readability over the 3d view
function drawTextShadow(ctx, text, x, y, color, scale) {
  scale = scale || 1;
  drawText(ctx, text, x + scale, y + scale, '#000000', scale);
  drawText(ctx, text, x, y, color, scale);
}

function drawTextCentered(ctx, text, cx, y, color, scale) {
  const w = textWidth(text, scale);
  drawTextShadow(ctx, text, Math.round(cx - w / 2), y, color, scale);
}
